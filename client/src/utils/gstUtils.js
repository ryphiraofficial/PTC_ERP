export const formatINR = (val) => {
  const num = Number(val) || 0;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 2,
    minimumFractionDigits: 2,
  }).format(num);
};

export const formatDate = (dateString) => {
  if (!dateString) return '-';
  const d = new Date(dateString);
  return d.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
};

export const getStateFromCode = (code) => {
  const match = GST_STATES.find((s) => s.code === String(code).padStart(2, '0'));
  return match ? match.name : '';
};

export const getStateCodeFromGstin = (gstin) => {
  if (gstin && gstin.length >= 2) {
    const code = gstin.substring(0, 2);
    const valid = GST_STATES.find((s) => s.code === code);
    if (valid) return { code, state: valid.name };
  }
  return null;
};

export const isValidGSTIN = (gstin) => {
  if (!gstin) return false;
  const regex = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/;
  return regex.test(gstin.trim());
};
